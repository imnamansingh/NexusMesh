// orchestrator/src/services/ledgerService.js
import { ethers } from "ethers";
import ledgerArtifact from "../../../contracts/artifacts/contracts/NexusMeshLedger.sol/NexusMeshLedger.json" assert { type: "json" };

// Connect to EVM Blockchain Provider (Read-Only)
const provider = new ethers.JsonRpcProvider(process.env.RPC_URL || "http://127.0.0.1:8545");
const contractAddress = process.env.CONTRACT_ADDRESS;

// Read-only contract interface
const ledgerContract = new ethers.Contract(contractAddress, ledgerArtifact.abi, provider);

/**
 * Helper function used by Orchestrator middleware 
 * to verify if a daemon wallet is registered on the blockchain.
 */
export async function checkNodeOnChain(nodeAddress) {
    try {
        // Calls the public getter generated by Solidity for `mapping public nodes`
        const nodeInfo = await ledgerContract.nodes(nodeAddress);
        
        // Returns true if `isRegistered` flag is true on-chain
        return nodeInfo.isRegistered; 
    } catch (error) {
        console.error("Error querying blockchain:", error);
        return false;
    }
}

async function daemonAuthMiddleware(req, res, next) {
    const { payload, signature } = req.body;

    // A. Anti-Replay Attack Check (Reject pings older than 30 seconds)
    if (Math.abs(Date.now() - payload.timestamp) > 30000) {
        return res.status(401).json({ error: "Timestamp expired or clock skew" });
    }

    // B. Recover Signer Wallet
    const messageHash = ethers.keccak256(ethers.toUtf8Bytes(JSON.stringify(payload)));
    const recoveredAddress = ethers.verifyMessage(ethers.getBytes(messageHash), signature);

    if (recoveredAddress.toLowerCase() !== payload.nodeAddress.toLowerCase()) {
        return res.status(401).json({ error: "Invalid signature" });
    }

    // C. On-Chain Verification (Check if node is registered in Smart Contract or cached DB)
    const isRegistered = await checkNodeOnChain(recoveredAddress);
    if (!isRegistered) {
        return res.status(403).json({ error: "Node wallet not registered on-chain" });
    }

    // Success! Pass node details to the route handler
    req.nodeAddress = recoveredAddress;
    next();
}